#!/usr/bin/env bash
# Extract hardcoded prompt-like strings from the Claude Code single-file binary.
#
# The binary is a Bun-compiled executable with the whole JS bundle embedded, so
# `strings` yields tens of thousands of lines: code, identifiers, error text, UI
# copy, AND the model-facing prompt strings. This filters heuristically for the
# natural-language / instruction-like prose that reads as a prompt.
#
# Heuristic — keep a line if EITHER:
#   (strong) it carries a known prompt marker (You are / Your task / IMPORTANT /
#            Do NOT / <system-reminder> / <example> ...), OR
#   (prose)  it's long, mostly letters, many words, and low on code punctuation.
#
# Output is intentionally over-inclusive: comprehensiveness over precision.
# Tune MINWORDS / ALPHA / CODE below to trade recall for noise.
#
# Usage: extract-claude-code-prompts.sh <binary> <out.md>

set -euo pipefail

BIN="${1:?path to claude binary (bin/claude.exe)}"
OUT="${2:?output .md path}"

RAW="$(mktemp)"
trap 'rm -f "$RAW"' EXIT

strings -n 30 "$BIN" | awk '
{
  n=length($0)
  # Drop too-short noise and the megabyte-long minified-code lines outright.
  if (n < 40 || n > 8000) next

  s=$0; alpha=gsub(/[A-Za-z]/,"&",s)
  s=$0; code =gsub(/[{}<>=$()\[\]|&`~^\\;]/,"&",s)
  ar=alpha/n; cr=code/n

  wc=0; m=split($0,a,/[ ]+/)
  for(i=1;i<=m;i++) if (a[i] ~ /[A-Za-z]/) wc++

  strong = ($0 ~ /(You are |Your task|You should|You must|You can |You will |Do NOT|Do not |IMPORTANT|CRITICAL|Never |Always |When you|Make sure|Note that|Remember|Please |Ensure |should not|must not|Respond |Summarize|Use the |<system-reminder>|<example>|<analysis>|<summary>|<thinking>|<budget|<persona|<task>)/)
  prose  = (wc >= 8 && ar >= 0.62 && cr <= 0.06)

  # A marker substring can appear inside minified code too, so still require the
  # line to read mostly like prose (loose thresholds) before keeping it.
  keep = prose || (strong && wc >= 5 && ar >= 0.45 && cr <= 0.15)

  if (keep) print $0
}' | awk '!seen[$0]++' > "$RAW"

LINES=$(wc -l < "$RAW")

# Pick a fence longer than any backtick run that appears in the data, so prompt
# strings that themselves contain ``` don't break the code block.
maxrun=$(grep -oE '`+' "$RAW" | awk '{ if (length>m) m=length } END{ print m+0 }')
fence=$(printf '%*s' $((maxrun+1>3 ? maxrun+1 : 3)) '' | tr ' ' '`')

{
  echo "# Claude Code — hardcoded prompt-like strings (heuristic extraction)"
  echo
  echo "Auto-generated by \`extract-claude-code-prompts.sh\`. Source binary:"
  echo "\`@anthropic-ai/claude-code\` \`bin/claude.exe\` (Bun single-file executable)."
  echo
  echo "These are \`strings\` candidates filtered for instruction-like prose, then"
  echo "deduplicated. The filter is over-inclusive on purpose — expect some UI/error"
  echo "copy mixed in, and note that template literals split on newlines so a single"
  echo "multi-line prompt appears as several consecutive lines. **$LINES** unique lines."
  echo "Re-run the script to regenerate; tune the heuristic there."
  echo
  echo "${fence}text"
  cat "$RAW"
  echo "${fence}"
} > "$OUT"

echo "wrote $LINES unique candidate lines -> $OUT"
